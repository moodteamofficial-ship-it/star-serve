#!/usr/bin/env bash
# Deploy (or update) the StarServe SPA on Cloud Run.
# Usage: deploy-frontend.sh <staging|production|backup> [image] [api_upstream_host]
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=config.sh
source "${SCRIPT_DIR}/config.sh"

ENV_NAME="${1:-}"
require_env_name "${ENV_NAME}"
IMAGE="${2:-$(web_image_base):${ENV_NAME}}"
SERVICE="$(web_service_name "${ENV_NAME}")"
SA="$(runtime_sa "${ENV_NAME}")"

DEFAULT_API_HOST="starserve-api-staging-233389149626.europe-west1.run.app"
if [ "${ENV_NAME}" = "production" ]; then
  DEFAULT_API_HOST="starserve-api-233389149626.europe-west1.run.app"
fi
API_UPSTREAM="${3:-${API_UPSTREAM:-${DEFAULT_API_HOST}}}"
API_UPSTREAM="$(printf '%s' "${API_UPSTREAM}" | sed -e 's|^https://||' -e 's|^http://||' -e 's|/.*||')"

MIN_INSTANCES=0
MAX_INSTANCES=10
MEMORY=512Mi
if [ "${ENV_NAME}" = "production" ]; then
  MIN_INSTANCES=1
  MAX_INSTANCES=20
  MEMORY=512Mi
fi

log "Deploying ${SERVICE} (${ENV_NAME}) image=${IMAGE} api=${API_UPSTREAM}"

gcloud run deploy "${SERVICE}" \
  --project="${GCP_PROJECT}" \
  --region="${GCP_REGION}" \
  --image="${IMAGE}" \
  --service-account="${SA}" \
  --port=8080 \
  --cpu=1 \
  --memory="${MEMORY}" \
  --concurrency=80 \
  --min-instances="${MIN_INSTANCES}" \
  --max-instances="${MAX_INSTANCES}" \
  --timeout=180 \
  --cpu-boost \
  --execution-environment=gen2 \
  --allow-unauthenticated \
  --ingress=all \
  --set-env-vars="API_UPSTREAM=${API_UPSTREAM}" \
  --quiet

URL="$(gcloud run services describe "${SERVICE}" \
  --project="${GCP_PROJECT}" \
  --region="${GCP_REGION}" \
  --format='value(status.url)')"

# Point staging/production API CORS + email deep-links at this SPA origin.
# Include both Cloud Run URL forms (project-number and hash) — browsers may use either.
# Prefer the project-number URL for EMAIL_APP_URL (stable deep-links in mail CTAs).
# Use ^||^ delimiter so commas inside CORS_ORIGINS are preserved.
log "Updating API CORS_ORIGINS / EMAIL_APP_URL for ${ENV_NAME}"
API_SERVICE="$(service_name "${ENV_NAME}")"
LOCAL_ORIGINS="http://localhost:5173,http://127.0.0.1:5173"
PROJECT_NUMBER="$(gcloud projects describe "${GCP_PROJECT}" --format='value(projectNumber)' 2>/dev/null || true)"
CORS_ORIGINS="${LOCAL_ORIGINS},${URL}"
EMAIL_APP_URL="${URL}"
if [ -n "${PROJECT_NUMBER}" ]; then
  ALT_URL="https://$(web_service_name "${ENV_NAME}")-${PROJECT_NUMBER}.${GCP_REGION}.run.app"
  if [ "${ALT_URL}" != "${URL}" ]; then
    CORS_ORIGINS="${CORS_ORIGINS},${ALT_URL}"
  fi
  # Canonical public app URL for email buttons (claim / Open Star Serve).
  EMAIL_APP_URL="${ALT_URL}"
fi
# Production SPA lives on Render at quote.*/dashboard — keep allowlisted for guest quotes.
if [ "${ENV_NAME}" = "production" ]; then
  CORS_ORIGINS="${CORS_ORIGINS},https://quote.starserveinsuranceagency.com,https://www.starserveinsuranceagency.com,https://starserveinsuranceagency.com,https://starserve-dashboard.onrender.com"
  EMAIL_APP_URL="https://quote.starserveinsuranceagency.com/dashboard"
fi
gcloud run services update "${API_SERVICE}" \
  --project="${GCP_PROJECT}" \
  --region="${GCP_REGION}" \
  --update-env-vars="^||^CORS_ORIGINS=${CORS_ORIGINS}||EMAIL_APP_URL=${EMAIL_APP_URL}" \
  --quiet

log "${ENV_NAME} frontend URL: ${URL}"
log "Email app URL: ${EMAIL_APP_URL}"
log "Health: ${URL}/ready"

python3 - "${ROOT_DIR}/frontend/.env.cloud" "${ENV_NAME}" "${URL}" <<'PY'
import sys
from pathlib import Path
path = Path(sys.argv[1])
path.parent.mkdir(parents=True, exist_ok=True)
env_name = sys.argv[2]
web_url = sys.argv[3].rstrip("/")
existing = {}
if path.exists():
    for line in path.read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.startswith("#"):
            k, v = line.split("=", 1)
            existing[k] = v
existing.setdefault("VITE_APP_NAME", "Star Serve")
existing.setdefault("VITE_DEFAULT_API_ENV", "staging")
existing["VITE_WEB_URL_" + env_name.upper()] = web_url
# Local SPA still uses relative /api via Vite proxy; document Cloud Run web URL.
path.write_text(
    "# Generated by scripts/gcp/deploy-frontend.sh — public URLs only, never secrets.\n"
    + "\n".join(f"{k}={existing[k]}" for k in sorted(existing))
    + "\n",
    encoding="utf-8",
)
print(f"[gcp] wrote {path} (web {env_name})")
PY

log "Open: ${URL}"
